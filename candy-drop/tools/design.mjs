// 角度约定：P(anchor, deg, len) 中 deg 为偏离铅垂线的角度，正值在右。

const rad = (deg) => (deg * Math.PI) / 180;
const R1 = (v) => Math.round(v * 10) / 10;
export const P = (a, deg, len) => [R1(a[0] + Math.sin(rad(deg)) * len), R1(a[1] + Math.cos(rad(deg)) * len)];

/** 两圆交点中靠下的那个，用于双绳悬挂的糖果初始位置（保证两根绳都恰好绷直） */
export function hangPoint(p1, r1, p2, r2) {
  const dx = p2[0] - p1[0];
  const dy = p2[1] - p1[1];
  const d = Math.hypot(dx, dy);
  const a = (r1 * r1 - r2 * r2 + d * d) / (2 * d);
  const h = Math.sqrt(Math.max(0, r1 * r1 - a * a));
  const ux = dx / d;
  const uy = dy / d;
  // 法向 n = (-uy, ux)，取下交点 p1 + a·u + h·n
  return [R1(p1[0] + a * ux - h * uy), R1(p1[1] + a * uy + h * ux)];
}

