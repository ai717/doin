export const strings = { zh, en };

export function htmlLang(locale) {
  return locale === "en" ? "en" : "zh-CN";
}

export function normalizeLocale(value) {
  return LOCALES.includes(value) ? value : "zh";
}

/** key 缺失时回退 zh，再缺失则回显 key 本身——绝不抛错、绝不空白。 */
export function translate(locale, key, vars) {
  const table = strings[normalizeLocale(locale)];
  const fallback = strings.zh;
  const raw = table[key] ?? fallback[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

export function hasKey(locale, key) {
  return key in (strings[locale] ?? {});
}

