export const strings = { zh, en };

export function translate(locale, key, vars) {
  const table = strings[locale] ?? strings.zh;
  const raw = table[key] ?? strings.zh[key] ?? key;
  if (!vars) return raw;
  return String(raw).replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match));
}

export const htmlLang = (locale) => (locale === "en" ? "en" : "zh-CN");
