// 森林冰火人 · 关卡数据（40 关手作精编）与解析器
// 统一 20 列 × 14 行模板：
//   row9  "..X..............Y.."   火出口X(2) 冰出口Y(17)
//   row10 "..#..............#.."   X/Y 门前平台
//   row11 "F.................C."   火人出生(0) 冰人出生(18) 机关区 col1-17
//   row12 "##................##"   地面/坑/冰面 col2-17
//   row13 底层实心
// 字符：. 空  # 实心  = 单向平台  M 岩浆  W 水  G 毒液  I 冰面  V 藤墙
//   F 火人出生  C 冰人出生  X 火出口  Y 冰出口
//   r 红宝石  b 蓝宝石  * 金宝石
//   o 压力板  d 红门  e 蓝门  D 中立门  s 同步板（两两配对） K 箱子
//   P 移动平台  T 传送门（两两配对）  Z 冻结点（冰人技能）
// 放置规则：门/按钮/同步板/箱子/藤墙/传送门放 row11（脚下须实心）；
//           宝石/冻结点/平台放 row10 悬浮；X/Y/F/C 脚下自动补支撑
// 开关配对：第 i 扇门由第 i 个开关控制（普通按钮 o 在前，随后同步板对 s）
import { T } from "./engine.mjs";

const E = T.EMPTY;

function parse(rows, opts = {}) {
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const map = [];
  for (let y = 0; y < h; y++) {
    const row = new Array(w).fill(E);
    for (let x = 0; x < rows[y].length; x++) {
      const t = charToTile(rows[y][x]);
      // row10 是出口平台层：实心 # 解析为单向平台（可从下方跳过、站在其上）
      row[x] = t === null ? E : y === 10 && t === T.SOLID ? T.ONEWAY : t;
    }
    map.push(row);
  }

  const level = {
    name: opts.name ?? "",
    w,
    h,
    map,
    fireX: 0,
    fireY: 0,
    iceX: 0,
    iceY: 0,
    fireExit: { x: 0, y: 0 },
    iceExit: { x: 0, y: 0 },
    gems: [],
    doors: [],
    buttons: [],
    syncPairs: [],
    crates: [],
    movers: [],
    portals: [],
    freezeSpots: []
  };

  let doorIdx = 0;
  let btnIdx = 0;
  let syncIdx = 0;
  let portalIdx = 0;
  let moverIdx = 0;

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x];
      const t = charToTile(ch);
      if (t !== null) {
        map[y][x] = y === 10 && t === T.SOLID ? T.ONEWAY : t;
        continue;
      }
      switch (ch) {
        case "F":
          level.fireX = x + 0.5;
          level.fireY = y + 1;
          break;
        case "C":
          level.iceX = x + 0.5;
          level.iceY = y + 1;
          break;
        case "X":
          level.fireExit = { x: x + 0.5, y: y + 1 };
          break;
        case "Y":
          level.iceExit = { x: x + 0.5, y: y + 1 };
          break;
        case "r":
          level.gems.push({ x: x + 0.5, y: y + 1.5, kind: "red" });
          break;
        case "b":
          level.gems.push({ x: x + 0.5, y: y + 1.5, kind: "blue" });
          break;
        case "*":
          level.gems.push({ x: x + 0.5, y: y + 1.5, kind: "gold" });
          break;
        case "o":
          level.buttons.push({ x: x + 0.5, y: y + 1 });
          btnIdx += 1;
          break;
        case "d":
          level.doors.push({ x: x + 0.5, y: y + 1, color: "red", switchIndex: doorIdx });
          doorIdx += 1;
          break;
        case "e":
          level.doors.push({ x: x + 0.5, y: y + 1, color: "blue", switchIndex: doorIdx });
          doorIdx += 1;
          break;
        case "D":
          level.doors.push({ x: x + 0.5, y: y + 1, color: "neutral", switchIndex: doorIdx });
          doorIdx += 1;
          break;
        case "s": {
          const pairIdx = Math.floor(syncIdx / 2);
          const which = syncIdx % 2;
          if (!level.syncPairs[pairIdx]) {
            level.syncPairs.push({ a: null, b: null, switchIndex: btnIdx });
          }
          const pair = level.syncPairs[pairIdx];
          const plate = { x: x + 0.5, y: y + 1 };
          if (which === 0) pair.a = plate;
          else pair.b = plate;
          syncIdx += 1;
          break;
        }
        case "K":
          level.crates.push({ x: x + 0.5, y: y + 1 });
          break;
        case "P": {
          const cfg = (opts.movers ?? [])[moverIdx] ?? { axis: "h", range: 2.5, speed: 1.2 };
          level.movers.push({ x: x + 0.5, y: y + 1.5, axis: cfg.axis, range: cfg.range, speed: cfg.speed });
          moverIdx += 1;
          break;
        }
        case "T":
          level.portals.push({ x: x + 0.5, y: y + 1, id: portalIdx });
          portalIdx += 1;
          break;
        case "Z":
          level.freezeSpots.push({ x: x + 0.5, y: y + 1 });
          break;
        default:
          break;
      }
    }
  }

  // 传送门两两配对（0<->1, 2<->3 ...）
  for (let i = 0; i + 1 < level.portals.length; i += 2) {
    level.portals[i].pairId = i + 1;
    level.portals[i + 1].pairId = i;
  }
  if (level.portals.length % 2 === 1) level.portals.pop();

  level.syncPairs = level.syncPairs.filter((p) => p.a && p.b);

  const switchCount = level.buttons.length + level.syncPairs.length;
  level.doors.forEach((d) => {
    if (d.switchIndex >= switchCount) d.switchIndex = -1;
  });

  // 自动补支撑：出生点/出口/传送门脚下的空格变为实心（坑上不补，留待自检报错）
  const supportSpots = [
    { x: level.fireX, y: level.fireY },
    { x: level.iceX, y: level.iceY },
    { x: level.fireExit.x, y: level.fireExit.y },
    { x: level.iceExit.x, y: level.iceExit.y },
    ...level.portals.map((p) => ({ x: p.x, y: p.y })),
    ...level.freezeSpots.map((z) => ({ x: z.x, y: z.y }))
  ];
  for (const s of supportSpots) {
    const r = Math.floor(s.y);
    const c = Math.floor(s.x);
    if (r < 0 || r >= h || c < 0 || c >= w) continue;
    const t = map[r][c];
    // 危险区（岩浆/水/毒）与空格都补实心，保证出生/出口/传送脚下可站
    if (t !== T.SOLID && t !== T.ONEWAY && t !== T.ICE && t !== T.VINE) {
      map[r][c] = T.SOLID;
    }
  }

  // X/Y 出口平台（row10 ONEWAY）脚下 row12 若为危险/空格则补实心，保证能跳上平台
  for (let c = 0; c < w; c++) {
    if (map[10][c] === T.ONEWAY) {
      const t = map[12][c];
      if (t !== T.SOLID && t !== T.ONEWAY && t !== T.ICE && t !== T.VINE) {
        map[12][c] = T.SOLID;
      }
    }
  }

  // 自动补齐宝石到 5 颗（2红 + 2蓝 + 1金），空缺按角色路线就近放置
  fillGems(level, rows);

  return level;
}

// 在角色可经过的空中补放宝石（row9-11 的空格），红在左侧、蓝在右侧、金在中央
function fillGems(level, rows) {
  const have = { red: 0, blue: 0, gold: 0 };
  level.gems.forEach((g) => {
    have[g.kind] += 1;
  });
  const need = 5 - level.gems.length;
  if (need <= 0) return;

  const want = { red: 2, blue: 2, gold: 1 };
  const miss = {
    red: Math.max(0, want.red - have.red),
    blue: Math.max(0, want.blue - have.blue),
    gold: Math.max(0, want.gold - have.gold)
  };
  const order = [];
  if (miss.red) order.push("red");
  if (miss.blue) order.push("blue");
  if (miss.gold) order.push("gold");
  const extras = ["red", "blue", "gold"];
  while (order.length < need) order.push(extras[order.length % 3]);

  const spots = [];
  for (let r = 9; r <= 11; r++) {
    for (let c = 2; c < level.w - 2; c++) {
      if ((rows[r]?.[c] ?? "") === ".") spots.push({ r, c });
    }
  }
  const take = (pred) => {
    const idx = spots.findIndex(pred);
    if (idx < 0) return spots.shift();
    const s = spots[idx];
    spots.splice(idx, 1);
    return s;
  };

  for (const kind of order.slice(0, need)) {
    const s =
      kind === "red"
        ? take((p) => p.c < 9)
        : kind === "blue"
          ? take((p) => p.c >= 9)
          : take((p) => p.c >= 7 && p.c <= 12);
    if (s) level.gems.push({ x: s.c + 0.5, y: s.r + 1.5, kind });
  }
}

function charToTile(ch) {
  switch (ch) {
    case ".": return E;
    case " ": return E;
    case "#": return T.SOLID;
    case "=": return T.ONEWAY;
    case "M": return T.MAGMA;
    case "W": return T.WATER;
    case "G": return T.GOO;
    case "I": return T.ICE;
    case "V": return T.VINE;
    default: return null;
  }
}

